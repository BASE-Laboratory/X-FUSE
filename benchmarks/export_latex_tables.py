def _fmt_stat(
    entry: dict[str, Any] | None,
    digits: int = 4,
    bold: bool = False,
) -> str:
    if not entry or "mean" not in entry:
        return "---"
    mean = float(entry["mean"])
    std = float(entry.get("std", 0.0))
    txt = f"{mean:.{digits}f} $\\pm$ {std:.{digits}f}"
    return f"\\textbf{{{txt}}}" if bold else txt


def _best_key(
    rows: list[str],
    getter: Any,
    higher_is_better: bool = True,
) -> str | None:
    best_k: str | None = None
    best_v: float | None = None
    for rk in rows:
        ent = getter(rk)
        if not ent or "mean" not in ent:
            continue
        val = float(ent["mean"])
        if (
            best_v is None
            or (higher_is_better and val > best_v)
            or ((not higher_is_better) and val < best_v)
        ):
            best_v = val
            best_k = rk
    return best_k


def build_table1_regimes_and_ablations(
    design: dict[str, Any], referee: dict[str, Any]
) -> str:
    lines: list[str] = [
        "% Auto-generated by benchmarks.export_latex_tables",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        "\\caption{Architectural component ablations across spin-2 structure-tensor "
        "upsampling (oriented sub-PSF lamellae) and heavy-tailed forward PSF physics "
        "(mean $\\pm$ SD across 3 seeds).}",
        "\\label{tab:xfuse_ablations}",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Variant & Lamellar $8\\times$ mIoU & Lamellar $16\\times$ mIoU & "
        "Core+Halo $8\\times$ mIoU & Zn13X $8\\times$ Pearson $r$ \\\\",
        "\\midrule",
    ]
    sa = design.get("stage_a_upsampler", {})
    up_rows = [
        "scalar_dilated_jbu",
        "spin2_structure_tensor",
        "spin2_plus_subtoken",
        "learned_spin2_subtoken",
    ]
    b_l8 = _best_key(
        up_rows, lambda k: sa.get("lamellar_8x", {}).get(k, {}).get("mIoU")
    )
    b_l16 = _best_key(
        up_rows, lambda k: sa.get("lamellar_16x", {}).get(k, {}).get("mIoU")
    )
    for rk in up_rows:
        e8 = sa.get("lamellar_8x", {}).get(rk, {}).get("mIoU")
        e16 = sa.get("lamellar_16x", {}).get(rk, {}).get("mIoU")
        lines.append(
            f"{METHOD_LABELS.get(rk, rk)} & "
            f"{_fmt_stat(e8, 4, rk == b_l8)} & "
            f"{_fmt_stat(e16, 4, rk == b_l16)} & --- & --- \\\\"
        )

    lines.append("\\midrule")
    sb = design.get("stage_b_psf_physics", {})
    psf_rows = ["fixed_gaussian", "learn_gaussian", "learn_moffat", "learn_core_halo"]
    b_ch = _best_key(
        psf_rows, lambda k: sb.get("core_halo_probe_8x", {}).get(k, {}).get("mIoU")
    )
    b_zn = _best_key(
        psf_rows,
        lambda k: sb.get("zn13x_synchrotron_8x", {}).get(k, {}).get("pearson_r"),
    )
    for rk in psf_rows:
        ech = sb.get("core_halo_probe_8x", {}).get(rk, {}).get("mIoU")
        ezn = sb.get("zn13X_synchrotron_8x", {}) or sb.get("zn13x_synchrotron_8x", {})
        ezn_r = ezn.get(rk, {}).get("pearson_r")
        lines.append(
            f"{METHOD_LABELS.get(rk, rk)} & --- & --- & "
            f"{_fmt_stat(ech, 4, rk == b_ch)} & "
            f"{_fmt_stat(ezn_r, 4, rk == b_zn)} \\\\"
        )

    # Append Regime B1 16x lamellar summary if referee evaluation is present
    b_sweep = referee.get("exp3_regime_b_lamellar_sweep", [])
    lam16_entry = next(
        (it for it in b_sweep if int(it.get("downsample_factor", 0)) == 16), None
    )
    if lam16_entry is not None:
        lines.append("\\midrule")
        lines.append(
            "\\multicolumn{5}{l}{\\emph{Regime B1 Iso-Intensity Lamellar Colony "
            "Benchmark ($16\\times$ Moffat Hold-Out):}} \\\\"
        )
        m16 = lam16_entry.get("methods", {})
        r_order = ["otsu", "bicubic", "jbu", "cnmf", "guided_tv", "siren_inr", "xfuse"]
        best_16 = _best_key(r_order, lambda k: m16.get(k, {}).get("miou"))
        best_bf = _best_key(r_order, lambda k: m16.get(k, {}).get("bf1"))
        for rk in r_order:
            if rk not in m16:
                continue
            lines.append(
                f"{METHOD_LABELS.get(rk, rk)} & --- & "
                f"{_fmt_stat(m16[rk].get('miou'), 4, rk == best_16)} & "
                f"BF1: {_fmt_stat(m16[rk].get('bf1'), 4, rk == best_bf)} & --- \\\\"
            )

    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}", ""])
    return "\n".join(lines)


def build_table2_real_trimodality(
    design: dict[str, Any], referee: dict[str, Any]
) -> str:
    se = design.get("stage_e_real_em", {})
    zn = referee.get("exp1_zn13x_guided_16x_holdout", {}).get("methods", {})
    ti = se.get("ti_rcca_5elem_stem_eds_8x", {}).get("methods", {})
    edx = se.get("edxia_lc3_6elem_sem_eds_8x", {}).get("methods", {})
    cuzn = se.get("cuzn_3d_eels_cube_4x", {}).get("methods", {})

    rows = ["otsu", "bicubic", "jbu", "cnmf", "guided_tv", "siren_inr", "xfuse"]
    b_zn = _best_key(rows, lambda k: zn.get(k, {}).get("pearson_r"))
    b_ti_r = _best_key(rows, lambda k: ti.get(k, {}).get("pearson_r"))
    b_ti_iou = _best_key(rows, lambda k: ti.get(k, {}).get("mIoU"))
    b_ed_r = _best_key(rows, lambda k: edx.get(k, {}).get("pearson_r"))
    b_ed_iou = _best_key(rows, lambda k: edx.get(k, {}).get("mIoU"))

    lines: list[str] = [
        "% Auto-generated by benchmarks.export_latex_tables",
        "\\begin{table*}[t]",
        "\\centering",
        "\\small",
        "\\caption{Tri-modality experimental validation across Synchrotron XCT+XRD-CT "
        "(\\texttt{Zn13X}, $16\\times$), Nanoscale HAADF-STEM+EDS (\\texttt{Ti-RCCA}, "
        "$8\\times$), Microscale SEM-BSE+EDS (\\texttt{EPFL edxia LC3}, $8\\times$), "
        "and 3D Core-Loss STEM-EELS (\\texttt{CuZn}, $4\\times$).}",
        "\\label{tab:xfuse_real_trimodality}",
        "\\begin{tabular}{lccccc}",
        "\\toprule",
        "Method & Zn13X XCT+XRD ($r$) & Ti-RCCA STEM-EDS ($r$) & "
        "Ti-RCCA mIoU & edxia SEM-EDS ($r$) & edxia mIoU \\\\",
        "\\midrule",
    ]
    for rk in rows:
        lines.append(
            f"{METHOD_LABELS.get(rk, rk)} & "
            f"{_fmt_stat(zn.get(rk, {}).get('pearson_r'), 4, rk == b_zn)} & "
            f"{_fmt_stat(ti.get(rk, {}).get('pearson_r'), 4, rk == b_ti_r)} & "
            f"{_fmt_stat(ti.get(rk, {}).get('mIoU'), 4, rk == b_ti_iou)} & "
            f"{_fmt_stat(edx.get(rk, {}).get('pearson_r'), 4, rk == b_ed_r)} & "
            f"{_fmt_stat(edx.get(rk, {}).get('mIoU'), 4, rk == b_ed_iou)} \\\\"
        )

    if cuzn:
        lines.append("\\midrule")
        lines.append(
            "\\multicolumn{6}{l}{\\emph{Simultaneous HAADF-STEM + 33-Channel 3D "
            "Core-Loss EELS Cube (\\texttt{CuZn}, $4\\times$ Coarse Pre-Edge "
            "Fit):}} \\\\"
        )
        eels_rows = [
            "nmf_bicubic",
            "nmf_jbu",
            "nmf_cnmf",
            "nmf_guided_tv",
            "nmf_siren_inr",
            "xfuse_joint_spectral",
        ]
        b_er = _best_key(eels_rows, lambda k: cuzn.get(k, {}).get("pearson_r"))
        b_ep = _best_key(eels_rows, lambda k: cuzn.get(k, {}).get("psnr_db"))
        b_es = _best_key(eels_rows, lambda k: cuzn.get(k, {}).get("support_iou"))
        for rk in eels_rows:
            if rk not in cuzn:
                continue
            lines.append(
                f"{METHOD_LABELS.get(rk, rk)} & "
                f"$r$: {_fmt_stat(cuzn[rk].get('pearson_r'), 4, rk == b_er)} & "
                f"PSNR: {_fmt_stat(cuzn[rk].get('psnr_db'), 2, rk == b_ep)} & "
                f"IoU: {_fmt_stat(cuzn[rk].get('support_iou'), 4, rk == b_es)} & "
                "--- & --- \\\\"
            )

    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""])
    return "\n".join(lines)


def build_table3_volumetric_and_active(design: dict[str, Any]) -> str:
    sc = design.get("stage_c_volumetric", {})
    vv = sc.get("volumetric_variants", {})
    curve = sc.get("localized_reaction_active_curve_z48", {})

    v_rows = ["sparse_25d_baseline", "depth_psf_deconv", "depth_psf_plus_triplane"]
    b_all = _best_key(v_rows, lambda k: vv.get(k, {}).get("mIoU_3d"))
    b_ung = _best_key(v_rows, lambda k: vv.get(k, {}).get("mIoU_unguided"))
    b_zc = _best_key(v_rows, lambda k: vv.get(k, {}).get("z_consistency"))

    lines: list[str] = [
        "% Auto-generated by benchmarks.export_latex_tables",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        "\\caption{Volumetric axial-PSF deconvolution ($20\\times 48\\times 48$, "
        "$\\sigma_z = 2.6$) and multi-budget active beamtime steering on a $Z=48$ "
        "tomogram with a localized reaction front ($z \\in [26, 38)$).}",
        "\\label{tab:xfuse_volumetric_active}",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "3D Configuration / Budget & 3D mIoU & Unguided-$Z$ mIoU / Phase-C IoU & "
        "$Z$-Consistency \\\\",
        "\\midrule",
    ]
    for rk in v_rows:
        lines.append(
            f"{METHOD_LABELS.get(rk, rk)} & "
            f"{_fmt_stat(vv.get(rk, {}).get('mIoU_3d'), 4, rk == b_all)} & "
            f"{_fmt_stat(vv.get(rk, {}).get('mIoU_unguided'), 4, rk == b_ung)} & "
            f"{_fmt_stat(vv.get(rk, {}).get('z_consistency'), 4, rk == b_zc)} \\\\"
        )

    if curve:
        lines.append("\\midrule")
        lines.append(
            "\\multicolumn{4}{l}{\\emph{Active Slice Steering vs.\\ Equispaced "
            "Schedule ($Z=48$, Reaction Band $z \\in [26, 38)$):}} \\\\"
        )
        act_d = curve.get("active_steering", {})
        eq_d = curve.get("equispaced", {})
        for bk in sorted(act_d.keys(), key=lambda x: int(x)):
            am = act_d.get(bk, {}).get("mIoU_3d")
            ac = act_d.get(bk, {}).get("phase_c_iou")
            em = eq_d.get(bk, {}).get("mIoU_3d")
            ec = eq_d.get(bk, {}).get("phase_c_iou")
            act_wins_m = bool(am and em and float(am["mean"]) >= float(em["mean"]))
            act_wins_c = bool(ac and ec and float(ac["mean"]) >= float(ec["mean"]))
            lines.append(
                f"Budget $k={bk}$ (Equispaced) & "
                f"{_fmt_stat(em, 4, not act_wins_m)} & "
                f"{_fmt_stat(ec, 4, not act_wins_c)} & --- \\\\"
            )
            lines.append(
                f"Budget $k={bk}$ (Active Steering) & "
                f"{_fmt_stat(am, 4, act_wins_m)} & "
                f"{_fmt_stat(ac, 4, act_wins_c)} & --- \\\\"
            )

    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}", ""])
    return "\n".join(lines)


def build_table4_conformal_uq(design: dict[str, Any]) -> str:
    sd = design.get("stage_d_conformal", {})
    syn = sd.get("synthetic_lamellar_8x", {})
    eds = sd.get("real_ti_rcca_fig3a_to_fig3b_5class", {})
    c_rows = ["raw_lac", "raw_aps", "temp_raps_block"]

    lines: list[str] = [
        "% Auto-generated by benchmarks.export_latex_tables",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        "\\caption{Cross-specimen conformal prediction validity and interior sharpness "
        "comparing uncalibrated LAC/APS against spatial-block temperature-scaled "
        "RAPS.}",
        "\\label{tab:xfuse_conformal}",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Calibrator & Empirical Cov. & Mean Set Size $|\\mathcal{C}|$ & "
        "Boundary $|\\mathcal{C}|$ & Interior Singleton \\% \\\\",
        "\\midrule",
        "\\multicolumn{5}{l}{\\emph{Synthetic Oriented Lamellar ($8\\times$, "
        "Nominal $1 - \\alpha = 0.90$, $K=3$):}} \\\\",
    ]
    for rk in c_rows:
        d10 = syn.get(rk, {}).get("0.10", {})
        cov = d10.get("empirical_coverage")
        is_best = bool(cov and float(cov["mean"]) >= 0.90 and rk == "temp_raps_block")
        lines.append(
            f"{METHOD_LABELS.get(rk, rk)} & "
            f"{_fmt_stat(cov, 4, is_best)} & "
            f"{_fmt_stat(d10.get('mean_set_size'), 4, is_best)} & "
            f"{_fmt_stat(d10.get('boundary_mean_set_size'), 4)} & "
            f"{_fmt_stat(d10.get('interior_singleton_fraction'), 4, is_best)} \\\\"
        )

    lines.append("\\midrule")
    lines.append(
        "\\multicolumn{5}{l}{\\emph{Real Cross-Alloy Ti-RCCA STEM-EDS "
        "(\\texttt{Fig3a} $\\rightarrow$ \\texttt{Fig3b}, Nominal "
        "$1 - \\alpha = 0.80$, $K=5$):}} \\\\"
    )
    for rk in c_rows:
        d20 = eds.get(rk, {}).get("0.20", {})
        cov = d20.get("empirical_coverage")
        is_best = bool(cov and float(cov["mean"]) >= 0.80 and rk == "temp_raps_block")
        lines.append(
            f"{METHOD_LABELS.get(rk, rk)} & "
            f"{_fmt_stat(cov, 4, is_best)} & "
            f"{_fmt_stat(d20.get('mean_set_size'), 4, is_best)} & "
            f"{_fmt_stat(d20.get('boundary_mean_set_size'), 4)} & "
            f"{_fmt_stat(d20.get('interior_singleton_fraction'), 4, is_best)} \\\\"
        )

    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}", ""])
    return "\n".join(lines)


def export_all_tables(
    design_json: Path,
    referee_json: Path,
    out_dir: Path,
) -> dict[str, Path]:
    design = (
        json.loads(design_json.read_text(encoding="utf-8"))
        if design_json.exists()
        else {}
    )
    referee = (
        json.loads(referee_json.read_text(encoding="utf-8"))
        if referee_json.exists()
        else {}
    )
    out_dir.mkdir(parents=True, exist_ok=True)

    rendered = {
        "table1_regimes_and_ablations.tex": build_table1_regimes_and_ablations(
            design, referee
        ),
        "table2_real_trimodality_benchmarks.tex": build_table2_real_trimodality(
            design, referee
        ),
        "table3_volumetric_and_active_tomo.tex": build_table3_volumetric_and_active(
            design
        ),
        "table4_conformal_uq.tex": build_table4_conformal_uq(design),
    }
    paths: dict[str, Path] = {}
    combined_chunks: list[str] = []
    for fname, content in rendered.items():
        p = out_dir / fname
        p.write_text(content, encoding="utf-8")
        paths[fname] = p
        combined_chunks.append(content)

    combined_path = out_dir / "manuscript_tables.tex"
    combined_path.write_text("\n".join(combined_chunks), encoding="utf-8")
    paths["manuscript_tables.tex"] = combined_path
    return paths


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Export X-FUSE benchmark JSON results as booktabs LaTeX tables."
    )
    parser.add_argument(
        "--design-json",
        type=Path,
        default=Path(
            "benchmarks/outputs/design_ablations/design_ablations_results.json"
        ),
    )
    parser.add_argument(
        "--referee-json",
        type=Path,
        default=Path(
            "benchmarks/outputs/referee_evaluation/referee_evaluation_results.json"
        ),
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("benchmarks/outputs/tables"),
    )
    args = parser.parse_args(argv)
    written = export_all_tables(args.design_json, args.referee_json, args.out_dir)
    print(json.dumps({k: str(v) for k, v in written.items()}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
